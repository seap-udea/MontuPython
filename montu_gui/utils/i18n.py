def normalize_lang(lang: str | None) -> str:
    if not lang:
        return _DEFAULT_LANG
    low = str(lang).strip().lower()
    return low if low in _SUPPORTED_LANGS else _DEFAULT_LANG


def get_language() -> str:
    return _current_lang


def set_language(lang: str) -> str:
    global _current_lang
    _current_lang = normalize_lang(lang)
    return _current_lang


def init_language_from_config(config: dict[str, Any] | None = None) -> str:
    cfg = config if isinstance(config, dict) else load_config()
    app = cfg.get("app", {}) if isinstance(cfg, dict) else {}
    lang = app.get("language", _DEFAULT_LANG) if isinstance(app, dict) else _DEFAULT_LANG
    return set_language(lang)


def tr(text: str) -> str:
    lang = get_language()
    if lang == "en":
        return text
    return _TRANSLATIONS.get(lang, {}).get(text, text)


def trf(text: str, **kwargs: Any) -> str:
    return tr(text).format(**kwargs)
